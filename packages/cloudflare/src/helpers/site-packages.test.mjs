import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { after, before, test } from "node:test";
import {
  copyMissingPackages,
  entryMatchesPackage,
  findSitePackagesDir,
  hasPackageArtifact,
  normalizePackageName,
} from "./site-packages.mjs";

let tmp;
before(async () => {
  tmp = await fs.mkdtemp(path.join(os.tmpdir(), "sitepkg-test-"));
});
after(async () => {
  await fs.rm(tmp, { recursive: true, force: true });
});

test("normalizePackageName folds case and separators", () => {
  assert.equal(normalizePackageName("PyYAML_x.Y"), "pyyaml-x-y");
});

test("entryMatchesPackage matches artifacts but not prefixed siblings", () => {
  assert.equal(entryMatchesPackage("pytest", "pytest"), true);
  assert.equal(entryMatchesPackage("pytest-8.0.dist-info", "pytest"), true);
  assert.equal(
    entryMatchesPackage("pytest_asyncio-1.0.dist-info", "pytest"),
    false,
  );
  assert.equal(
    hasPackageArtifact(["numpy", "pytest-8.0.dist-info"], "pytest"),
    true,
  );
});

test("findSitePackagesDir locates a nested site-packages", async () => {
  const sp = path.join(tmp, "snap", "lib", "python3.13", "site-packages");
  await fs.mkdir(sp, { recursive: true });
  assert.equal(await findSitePackagesDir(path.join(tmp, "snap")), sp);
});

test("copyMissingPackages copies RECORD files, skipping vendored/skip packages", async () => {
  const site = path.join(tmp, "site");
  const vendor = path.join(tmp, "vendor");
  await fs.mkdir(vendor, { recursive: true });

  // package "fresh" — should be copied
  await fs.mkdir(path.join(site, "fresh"), { recursive: true });
  await fs.writeFile(path.join(site, "fresh", "__init__.py"), "F");
  await fs.mkdir(path.join(site, "fresh-1.0.dist-info"), { recursive: true });
  await fs.writeFile(
    path.join(site, "fresh-1.0.dist-info", "METADATA"),
    "Name: fresh\n",
  );
  await fs.writeFile(
    path.join(site, "fresh-1.0.dist-info", "RECORD"),
    "fresh/__init__.py,sha256=abc,1\nfresh-1.0.dist-info/METADATA,,\n",
  );

  // package "already" — present in vendor, should be skipped
  await fs.mkdir(path.join(vendor, "already"), { recursive: true });
  await fs.mkdir(path.join(site, "already-2.0.dist-info"), { recursive: true });
  await fs.writeFile(
    path.join(site, "already-2.0.dist-info", "METADATA"),
    "Name: already\n",
  );
  await fs.writeFile(
    path.join(site, "already-2.0.dist-info", "RECORD"),
    "already/__init__.py,,\n",
  );

  // package "micropip" — in skip list
  await fs.mkdir(path.join(site, "micropip-1.dist-info"), { recursive: true });
  await fs.writeFile(
    path.join(site, "micropip-1.dist-info", "METADATA"),
    "Name: micropip\n",
  );
  await fs.writeFile(
    path.join(site, "micropip-1.dist-info", "RECORD"),
    "micropip/__init__.py,,\n",
  );
  await fs.mkdir(path.join(site, "micropip"), { recursive: true });
  await fs.writeFile(path.join(site, "micropip", "__init__.py"), "M");

  const copied = await copyMissingPackages(site, vendor, ["micropip"]);

  assert.deepEqual(copied, ["fresh"]);
  assert.equal(
    await fs.readFile(path.join(vendor, "fresh", "__init__.py"), "utf8"),
    "F",
  );
  assert.equal(
    await fs.readFile(
      path.join(vendor, "fresh-1.0.dist-info", "METADATA"),
      "utf8",
    ),
    "Name: fresh\n",
  );
});

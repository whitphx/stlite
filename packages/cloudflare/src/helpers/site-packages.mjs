import fs from "node:fs/promises";
import path from "node:path";

/** Normalize a package/distribution name for comparison (PEP 503-ish). */
export function normalizePackageName(name) {
  return name.toLowerCase().replace(/[-_.]+/g, "-");
}

/**
 * Whether a top-level `python_modules` entry (a package dir, a single-module
 * `.py`, or a `*.dist-info`/`*.egg-info`) belongs to `packageName`.
 */
export function entryMatchesPackage(entryName, packageName) {
  const normalizedPackage = normalizePackageName(packageName);
  const stripped = entryName
    .replace(/\.(dist-info|egg-info)$/, "")
    .replace(/\.py$/, "");
  const normalizedEntry = normalizePackageName(stripped);
  if (normalizedEntry === normalizedPackage) return true;
  // "<name>-<version>" artifacts such as dist-info dirs; requiring a digit right
  // after the dash keeps e.g. "pytest" from matching "pytest-asyncio".
  return (
    normalizedEntry.startsWith(`${normalizedPackage}-`) &&
    /^\d/.test(normalizedEntry.slice(normalizedPackage.length + 1))
  );
}

/** Whether any of `entries` is an artifact of `packageName`. */
export function hasPackageArtifact(entries, packageName) {
  return entries.some((entry) => entryMatchesPackage(entry, packageName));
}

/** Recursively locate the `site-packages` directory under `root`. */
export async function findSitePackagesDir(root) {
  const entries = await fs.readdir(root, { withFileTypes: true });
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const entryPath = path.join(root, entry.name);
    if (entry.name === "site-packages") return entryPath;
    try {
      return await findSitePackagesDir(entryPath);
    } catch {
      // Not in this subtree; keep looking.
    }
  }
  throw new Error(`site-packages directory not found under ${root}`);
}

/**
 * Copy every package present in `sitePackagesDir` but missing from `vendorDir`
 * (skipping `skipPackages` and anything already vendored) into `vendorDir`,
 * preserving each file's path from its `.dist-info/RECORD`. Returns the names
 * copied. Replaces the `python3` heredoc that did this before.
 *
 * @param {string} sitePackagesDir
 * @param {string} vendorDir
 * @param {string[]} skipPackages
 * @returns {Promise<string[]>}
 */
export async function copyMissingPackages(
  sitePackagesDir,
  vendorDir,
  skipPackages,
) {
  const skip = new Set(skipPackages.map(normalizePackageName));
  const vendorEntries = await fs.readdir(vendorDir);
  const siteEntries = await fs.readdir(sitePackagesDir);
  const distInfos = siteEntries.filter((name) => name.endsWith(".dist-info"));
  const copied = [];

  for (const distInfo of distInfos) {
    const distInfoDir = path.join(sitePackagesDir, distInfo);

    const packageName = await readMetadataName(
      path.join(distInfoDir, "METADATA"),
    );
    if (packageName == null) continue;
    if (
      skip.has(normalizePackageName(packageName)) ||
      hasPackageArtifact(vendorEntries, packageName)
    ) {
      continue;
    }

    let record;
    try {
      record = await fs.readFile(path.join(distInfoDir, "RECORD"), "utf8");
    } catch {
      continue;
    }

    for (const relPath of recordPaths(record)) {
      const source = path.resolve(sitePackagesDir, relPath);
      const relFromSite = path.relative(sitePackagesDir, source);
      if (relFromSite.startsWith("..") || path.isAbsolute(relFromSite))
        continue;
      let stat;
      try {
        stat = await fs.stat(source);
      } catch {
        continue;
      }
      if (!stat.isFile()) continue;
      const dest = path.join(vendorDir, relFromSite);
      await fs.mkdir(path.dirname(dest), { recursive: true });
      await fs.copyFile(source, dest);
    }

    copied.push(packageName);
  }

  return copied;
}

async function readMetadataName(metadataPath) {
  let metadata;
  try {
    metadata = await fs.readFile(metadataPath, "utf8");
  } catch {
    return null;
  }
  const match = metadata.match(/^Name:[ \t]*(.+)$/m);
  return match ? match[1].trim() : null;
}

/** First field (the path) of each non-empty RECORD row, CSV-quoting aware. */
function recordPaths(recordText) {
  const paths = [];
  for (const line of recordText.split(/\r?\n/)) {
    if (!line) continue;
    let firstField;
    if (line[0] === '"') {
      let i = 1;
      let value = "";
      while (i < line.length) {
        if (line[i] === '"') {
          if (line[i + 1] === '"') {
            value += '"';
            i += 2;
            continue;
          }
          break;
        }
        value += line[i];
        i += 1;
      }
      firstField = value;
    } else {
      const comma = line.indexOf(",");
      firstField = comma === -1 ? line : line.slice(0, comma);
    }
    if (firstField) paths.push(firstField);
  }
  return paths;
}
